// Builds src/puzzle-pages.js (the three pages with CSS/JS inlined) from the files in this folder.
// Run:  node src/puzzle-client/build.mjs     (then commit the regenerated src/puzzle-pages.js)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(dir, f), 'utf8');
const css = read('app.css');

function safeJs(name, js) {
  if (/<\/script/i.test(js)) throw new Error(name + ' contains </script');
  return js;
}
function html({ title, bodyClass, scripts }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="robots" content="noindex, nofollow">
<meta name="theme-color" content="#1a4a2e">
<title>${title}</title>
<link rel="icon" href="/favicon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Montserrat:wght@400;600;700;800;900&display=swap">
<style>
${css}
</style>
</head>
<body${bodyClass ? ` class="${bodyClass}"` : ''}>
<div id="app"></div>
<noscript><p style="padding:20px">This activity needs JavaScript. Please use a current phone browser.</p></noscript>
${scripts.map(([n, f]) => `<script>\n${safeJs(n, read(f))}\n</script>`).join('\n')}
</body>
</html>
`;
}

const pages = {
  PLAYER_HTML: html({ title: 'Team Connect Puzzle Challenge', scripts: [['player', 'player.js']] }),
  FACILITATOR_HTML: html({ title: 'Facilitator - Team Connect Puzzle Challenge', scripts: [['qrcode', 'qrcode.js'], ['facilitator', 'facilitator.js']] }),
  PROJECTOR_HTML: html({ title: 'Leaderboard - Team Connect Puzzle Challenge', bodyClass: 'proj', scripts: [['projector', 'projector.js']] }),
};

let out = '// GENERATED by src/puzzle-client/build.mjs - do not edit by hand. Edit the files in src/puzzle-client/ and re-run the build.\n';
for (const [k, v] of Object.entries(pages)) out += `export const ${k} = ${JSON.stringify(v)};\n`;
writeFileSync(join(dir, '..', 'puzzle-pages.js'), out);
console.log('wrote src/puzzle-pages.js', Object.fromEntries(Object.entries(pages).map(([k, v]) => [k, v.length])));
